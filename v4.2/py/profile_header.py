"""Emit the frozen profile into a freestanding C header consumed by E203 software."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def data():
    profiles=json.loads((ROOT/"py/profile42.json").read_text())["profiles"]
    lines=['/* Generated by py/profile_header.py from py/profile42.json. */','#ifndef KWT_V42_PROFILE_H',
           '#define KWT_V42_PROFILE_H','#include "kwt_v42_precision.h"','static const kwt_rice_profile kwt_v42_profiles[12]={']
    for p in profiles:
        lines.append('  {'+','.join(map(str,p['shifts']))+',{')
        for i in range(0,256,32):lines.append('    '+','.join(map(str,p["y_k"][i:i+32]))+',')
        lines.append('  }},')
    lines+=['};','#endif',''];return '\n'.join(lines).encode()
if __name__=="__main__":(ROOT/"integration/kwt_v42_profile.h").write_bytes(data())
